import AppKit
import UniformTypeIdentifiers

/// Makes a picture that was copied lighter, so that what is pasted is.
///
/// Only the kinds of thing on the clipboard are looked at until one of them is
/// a picture on its own. Text is never read, nor anything its owner marked as
/// private.
@MainActor
final class ClipboardLighter {
  struct Made {
    let file: URL
    let before: Int64
    let after: Int64
    fileprivate let original: [NSPasteboard.PasteboardType: Data]
    fileprivate let count: Int
  }

  private static let mark = NSPasteboard.PasteboardType("com.eugeniozamengo.Forge.lighter")
  private static let pictures: [NSPasteboard.PasteboardType] = [.png, .tiff]
  /// https://nspasteboard.org
  private static let hidden: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
  ]
  private static let words: Set<NSPasteboard.PasteboardType> = [.string, .rtf, .html, .fileURL, .URL]
  private static let interval: TimeInterval = 0.6

  private let board: NSPasteboard
  private let coordinator: ProcessingCoordinator
  private let folder: URL
  private var seen: Int
  private var timer: Timer?
  private var stops = 0

  init(board: NSPasteboard = .general, coordinator: ProcessingCoordinator, folder: URL? = nil) {
    self.board = board
    self.coordinator = coordinator
    self.folder = folder ?? Self.defaultFolder
    seen = board.changeCount - (folder == nil ? 0 : 1)
  }

  func start(_ then: @escaping (Made) -> Void) {
    guard timer == nil else { return }
    seen = board.changeCount
    clean()
    timer = Timer.scheduledTimer(withTimeInterval: Self.interval, repeats: true) { [weak self] _ in
      Task { @MainActor [weak self] in
        if let made = try? await self?.check() { then(made) }
      }
    }
  }

  func stop() {
    timer?.invalidate()
    timer = nil
    stops += 1
    clean()
  }

  /// What was copied is nobody's to find later: the pictures are kept only for
  /// the cards that show them.
  func discard(_ made: Made) { try? FileManager.default.removeItem(at: made.file) }

  static func leaveNothing() { try? FileManager.default.removeItem(at: defaultFolder) }

  private static let defaultFolder = FileManager.default.temporaryDirectory.appendingPathComponent("ForgeClipboard", isDirectory: true)

  private func clean() { try? FileManager.default.removeItem(at: folder) }

  /// Look once. Nil when there is nothing to do.
  func check() async throws -> Made? {
    let count = board.changeCount, stopsBefore = stops
    guard count != seen else { return nil }
    seen = count
    let types = board.types ?? []
    guard let type = Self.pictures.first(where: types.contains), Self.words.isDisjoint(with: types),
          !types.contains(Self.mark), !types.contains(where: { Self.hidden.contains($0.rawValue) }),
          let original = board.data(forType: type) else { return nil }

    let all = Self.pictures.reduce(into: [NSPasteboard.PasteboardType: Data]()) { $0[$1] = types.contains($1) ? board.data(forType: $1) : nil }
    try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
    let source = folder.appendingPathComponent("\(UUID().uuidString).\(type == .png ? "png" : "tiff")")
    try original.write(to: source)
    defer { try? FileManager.default.removeItem(at: source) }

    let file = try ProcessableFile(url: source)
    guard let lighter = try await Lighter.run(file, coordinator: coordinator, into: folder) else { return nil }
    // Whatever was copied while this was being worked on is what is wanted now.
    guard board.changeCount == count, stops == stopsBefore, let data = try? Data(contentsOf: lighter.outputURL) else {
      try? FileManager.default.removeItem(at: lighter.outputURL)
      return nil
    }
    let item = NSPasteboardItem()
    item.setData(data, forType: .init(UTType.jpeg.identifier))
    item.setData(Data(), forType: Self.mark)
    board.clearContents()
    board.writeObjects([item])
    seen = board.changeCount
    return Made(file: lighter.outputURL, before: file.fileSize, after: lighter.outputSize, original: all, count: seen)
  }

  /// Put the picture back as it was, unless something has been copied since.
  func undo(_ made: Made) -> Bool {
    guard board.changeCount == made.count else { return false }
    let item = NSPasteboardItem()
    made.original.forEach { item.setData($0.value, forType: $0.key) }
    item.setData(Data(), forType: Self.mark)
    board.clearContents()
    board.writeObjects([item])
    seen = board.changeCount
    return true
  }
}
